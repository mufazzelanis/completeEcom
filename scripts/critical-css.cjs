// Builds resources/css/critical-home.css: every rule of the compiled stylesheet that the
// homepage actually uses — checked in a real browser at phone and desktop width, in light and
// dark mode, after lazy sections have loaded. layouts/app.blade.php inlines it on the homepage
// and loads the full stylesheet without blocking the first paint (PageSpeed "render-blocking").
//
//   node scripts/critical-css.cjs [http://127.0.0.1:8000/]   (needs `php artisan serve` running)
//
// Re-run after `npm run build`. The output records which build it belongs to; if the build
// changes and this isn't re-run, the layout simply goes back to the normal blocking stylesheet.
const fs = require('fs');
const path = require('path');
const postcss = require('postcss');

const ROOT = path.resolve(__dirname, '..');
const URL = process.argv[2] || 'http://127.0.0.1:8000/';
const CHROME = process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe';
let puppeteer;
try { puppeteer = require('puppeteer-core'); } catch (e) { puppeteer = require(process.env.PUPPETEER_PATH); }

(async () => {
    const manifest = JSON.parse(fs.readFileSync(path.join(ROOT, 'public/build/manifest.json'), 'utf8'));
    const cssFile = manifest['resources/css/app.css'].file;
    const ast = postcss.parse(fs.readFileSync(path.join(ROOT, 'public/build', cssFile), 'utf8'));

    // every selector in the stylesheet, plus a "base element" form without pseudo-classes /
    // pseudo-elements (a :hover or ::before rule is kept when its element exists)
    const selectors = new Set();
    ast.walkRules((rule) => {
        if (rule.parent.type === 'atrule' && /keyframes/i.test(rule.parent.name)) return;
        rule.selectors.forEach((s) => selectors.add(s));
    });
    const strip = (s) => s.replace(/::?[a-z-]+(\((?:[^()]|\([^()]*\))*\))?/gi, (m) => (/^:(not|is|where|has)\(/i.test(m) ? m : ''))
        .replace(/\s+([>+~])\s*$/, '').trim() || '*';
    const list = [...selectors];

    const browser = await puppeteer.launch({ executablePath: CHROME, headless: 'new' });
    const used = new Set();
    for (const [width, mobile] of [[412, true], [1366, false]]) {
        for (const dark of [false, true]) {
            const page = await browser.newPage();
            await page.setViewport({ width, height: 900, isMobile: mobile, hasTouch: mobile });
            await page.goto(URL, { waitUntil: 'networkidle2', timeout: 60000 });
            await page.evaluate(async (dark) => {
                document.documentElement.classList.toggle('dark', dark);
                document.documentElement.classList.add('mv-live');
                for (let y = 0; y < document.body.scrollHeight; y += 500) { window.scrollTo(0, y); await new Promise((r) => setTimeout(r, 120)); }
                window.scrollTo(0, 0);
                await new Promise((r) => setTimeout(r, 600));
            }, dark);
            const hits = await page.evaluate((list, stripSrc) => {
                const strip = new Function('s', 'return (' + stripSrc + ')(s)');
                const ok = (s) => { try { return !!document.querySelector(s); } catch (e) { return false; } };
                return list.filter((s) => ok(s) || ok(strip(s)));
            }, list, strip.toString());
            hits.forEach((s) => used.add(s));
            await page.close();
        }
    }
    await browser.close();

    // keep used rules (with their @media / @supports wrappers), @font-face, @keyframes, @property
    ast.walkRules((rule) => {
        if (rule.parent.type === 'atrule' && /keyframes/i.test(rule.parent.name)) return;
        const keep = rule.selectors.filter((s) => used.has(s));
        if (!keep.length) rule.remove(); else rule.selectors = keep;
    });
    let changed = true;
    while (changed) { // drop wrappers left empty
        changed = false;
        ast.walkAtRules((at) => { if (/^(media|supports)$/i.test(at.name) && (!at.nodes || !at.nodes.length)) { at.remove(); changed = true; } });
    }
    const css = ast.toString().replace(/\/\*[\s\S]*?\*\//g, '').replace(/\s*\n\s*/g, '').replace(/\s{2,}/g, ' ');
    const out = `/* critical CSS for ${cssFile} — generated by scripts/critical-css.cjs, do not edit */\n` + css;
    fs.writeFileSync(path.join(ROOT, 'resources/css/critical-home.css'), out);
    console.log(`selectors: ${list.length}, used on homepage: ${used.size}; written ${Math.round(out.length / 1024)} KB (full: ${Math.round(fs.statSync(path.join(ROOT, 'public/build', cssFile)).size / 1024)} KB)`);
})().catch((e) => { console.error(e); process.exit(1); });
